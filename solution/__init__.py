"""Your solution.

The harness imports this package and calls `apply()` once, in the same process as `soup train`,
before Soup builds the model and the trainer. Patch whatever you need (transformers, peft,
bitsandbytes, Soup itself) so the training run uses your Triton kernels.

The rules in short (the README and the task statement have the full ones):
- your own `@triton.jit` kernels, defined in this folder, run in every measured run and together
  take >= 5% of the training time; the example's kernels (however renamed or rewritten) and
  kernels generated by torch.compile do not count;
- no ready-made kernel libraries (unsloth, liger-kernel, xformers, flash-attn, torchao, ...);
- the task stays the same: model, data, batches and their order, steps, LoRA, optimizer, Soup's
  settings and outputs; no other GPU, no background processes, no tricks with the measurement.
"""

def apply():
    import torch

    # Import-time bnb decorators only; restore before model setup and ordinary JIT launches.
    original_compile = torch.compile
    torch.compile = lambda fn=None, *args, **kwargs: (lambda value: value) if fn is None else fn
    try:
        import bitsandbytes  # noqa: F401
    finally:
        torch.compile = original_compile

    from .metadata_exact import install as install_metadata_exact
    install_metadata_exact()

    from .backend_choice import configure_blas
    configure_blas()

    from .runtime_compile import start_runtime_compile
    start_runtime_compile()

    from .activation_storage import patch_activation_storage
    from .ce import owned_aligned_ce
    from .chunked_head import (
        adapt_aligned_ce,
        patch_chunked_head,
        register_ce_backend,
        register_linear_backend,
    )
    from .dtype_cast import patch_quantized_casts

    register_ce_backend(adapt_aligned_ce(owned_aligned_ce))
    register_linear_backend(None)
    patch_chunked_head(chunk_size=512, compact=True, forward_gradient=True)
    from .selective_offload import patch_selective_offload
    patch_selective_offload(layers=28)
    patch_activation_storage(bits=4, block=64, wide_only=True, offload="selective")
    patch_quantized_casts()
    from .rmsnorm import patch_qwen_rmsnorm
    patch_qwen_rmsnorm()
    if torch.cuda.is_available():
        from .swiglu import patch_qwen2_mlp

        if not getattr(apply, "_sample_installed", False):
            patch_qwen2_mlp()  # starter helper; NOT our own kernel
            apply._sample_installed = True

    from .fp16_mlp import patch_fp16_mlp
    patch_fp16_mlp()
    from .mlp_unpadding import patch_tokenwise_mlp
    patch_tokenwise_mlp()

    from .lora_fusion import patch_vanilla_nf4_lora
    patch_vanilla_nf4_lora()

    from .gqa_native import patch_qwen_shared_kv
    patch_qwen_shared_kv()
    from .varlen_gqa import patch_qwen_varlen_attention
    patch_qwen_varlen_attention()

    from .rope_fusion import patch_qwen_rotary
    patch_qwen_rotary()

    from .dropout_bits import patch_lora_dropout_masks
    patch_lora_dropout_masks()

    from .packed_swiglu import patch_packed_swiglu
    patch_packed_swiglu()

    from .early_frozen_storage import patch_early_frozen_storage
    patch_early_frozen_storage()

    from .compact_decoder import patch_compact_decoder
    patch_compact_decoder()


    from .stream_loader import install as install_stream_weights
    install_stream_weights()
    from .host_head import patch_host_head
    patch_host_head(chunk_size=8192)
